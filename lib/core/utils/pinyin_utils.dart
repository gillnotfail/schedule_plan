  /// 取单个汉字的拼音首字母；未命中时返回该字符本身（保证回退稳定）。
  static String initialOf(String char) => _initials[char] ?? char.toLowerCase();

  /// 生成用于排序的拼音键：中文取首字母串，非中文保持原样。
  static String sortKey(String name) {
    if (name.isEmpty) {
      return '';
    }
    final buffer = StringBuffer();
    for (final rune in name.runes) {
      buffer.write(initialOf(String.fromCharCode(rune)));
    }
    return buffer.toString();
  }

  /// 比较两个姓名的拼音顺序。
  static int compareByName(String a, String b) => sortKey(a).compareTo(sortKey(b));
